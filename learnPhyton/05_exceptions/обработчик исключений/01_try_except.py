# Обработчик исключений. Конструкция "try - except"
# Исключения (exceptions) - это ошибки, которые возникают во время выполнения программы.
# Например: деление на ноль, обращение к несуществующему индексу, неправильный ввод данных.

# try - блок, в котором может возникнуть ошибка
# except - блок, который выполняется, если ошибка произошла

try:
    number = int(input('Введите число: '))
    result = 10 / number
    print('Результат:', result)
except ZeroDivisionError:
    print('Ошибка: деление на ноль!')
except ValueError:
    print('Ошибка: вы ввели не число!')

# Можно использовать общий блок except, если не нужно различать типы ошибок
try:
    value = int('abc')
    print(value)
except Exception as e:
    print('Произошла ошибка:', e)

# Блок else выполняется, если в try не было ошибок
try:
    x = 5
    y = 10
    print(x + y)
except TypeError:
    print('Ошибка типа данных')
else:
    print('Ошибок не было')

# Блок finally выполняется всегда: и при ошибке, и без неё
try:
    number = int('12')
    print(number)
except ValueError:
    print('Ошибка преобразования')
finally:
    print('Этот блок выполнится всегда')

# Пример с несколькими исключениями
try:
    data = [1, 2, 3]
    print(data[10])
except IndexError:
    print('Ошибка: индекс вне диапазона списка')
except Exception as e:
    print('Общая ошибка:', e)

# Важная мысль:
# Хорошая программа предвидит возможные ошибки и корректно обрабатывает их,
# чтобы не завершаться аварийно.
