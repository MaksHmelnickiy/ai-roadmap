# Числа в Python и их методы

# Целые числа
age = 25
print("Возраст:", age)

# Вещественные числа
price = 19.99
print("Цена:", price)

# Операции с числами
print("Сумма:", 10 + 5)
print("Разность:", 10 - 5)
print("Умножение:", 10 * 5)
print("Деление:", 10 / 5)
print("Целочисленное деление:", 10 // 3)
print("Остаток от деления:", 10 % 3)
print("Возведение в степень:", 2 ** 3)

# abs() - модуль числа
print("Модуль числа -7:", abs(-7))

# round() - округление
print("Округление 3.14159:", round(3.14159, 2))

# max() и min()
print("Максимум:", max(2, 8, 5))
print("Минимум:", min(2, 8, 5))

# pow() - возведение в степень
print("pow(2, 5):", pow(2, 5))

# Методы чисел
# У int и float есть методы, но не все методы используются так же часто
# Важно: числа не имеют большого количества методов, как строки или списки

num = 123
print("Число в строку:", str(num))
print("Тип числа:", type(num))

num_float = 12.3456
print("Форматирование float:", format(num_float, ".2f"))

# Пример с преобразованием строки в число
user_age = "30"
print("Преобразование строки в int:", int(user_age) + 5)
