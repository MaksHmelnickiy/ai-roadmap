# Функции строк. Индексы и срезы

text = 'Python'

# Индексы: отсчет начинается с 0.
print('Первый символ:', text[0])   # P — первый символ
print('Третий символ:', text[2])   # t — третий символ
print('Последний символ:', text[-1])  # n — последний символ

# Срезы: [начало:конец]. Символ с индексом «конец» не включается.
print('Первые три символа:', text[0:3])  # Pyt
print('Срез с третьего символа:', text[2:])   # thon — от индекса 2 до конца
print('Срез до четвёртого символа:', text[:4])   # Pyth — от начала до индекса 4
print('Каждый второй символ:', text[::2])  # Pto — каждый второй символ

# Основные функции и методы строк
name = '  Анна Иванова  '

print('Строка в нижнем регистре:', name.lower())       # переводит строку в нижний регистр
print('Строка в верхнем регистре:', name.upper())       # переводит строку в верхний регистр
print('Строка с заглавной буквы:', name.capitalize())  # делает первую букву заглавной, остальные — строчными
print('Строка без внешних пробелов:', name.strip())       # удаляет пробелы в начале и конце
print('Строка после замены имени:', name.replace('Анна', 'Мария'))  # заменяет часть строки
print('Количество букв «а»:', name.count('а'))    # считает количество символов
print('Индекс слова «Иван»:', name.find('Иван'))  # находит индекс начала текста
print('Строка, разделённая на список:', name.split(','))       # разделяет строку на список (массив)

words = ['Я', 'изучаю', 'Python']
print('Список объединён в строку:', ' '.join(words))  # объединяет элементы списка в строку через пробел
