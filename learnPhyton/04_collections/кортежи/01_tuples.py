# Кортежи (tuple)
# Кортеж похож на список, но его элементы нельзя изменять после создания.

# Обычно кортеж занимает меньше памяти, чем список с теми же элементами.
# Его удобно использовать для постоянных данных: координат, дней недели,
# настроек или фиксированных значений в серверном коде — там, где данные
# не должны случайно измениться.

colors = ('красный', 'зелёный', 'синий')

# Кортеж можно создать и без круглых скобок: главное — поставить запятые.
numbers = 1, 2, 3
print('Кортеж без круглых скобок:', numbers)  # (1, 2, 3)

# Для кортежа из одного элемента нужна запятая.
one_color = ('красный',)
print('Тип кортежа из одного элемента:', type(one_color))  # <class 'tuple'>
# Без запятой: ('красный') — это просто строка, а не кортеж.

# Список можно преобразовать в кортеж функцией ⁡⁣⁣⁢tuple()⁡.
fruits_list = ['яблоко', 'банан']
fruits_tuple = tuple(fruits_list)
print('Список преобразован в кортеж:', fruits_tuple)  # ('яблоко', 'банан')

# Получение элементов по индексу.
print('Первый цвет:', colors[0])   # красный
print('Последний цвет:', colors[-1])  # синий

# Кортеж можно перебрать в цикле.
for color in colors:
    print('Цвет из кортежа:', color)

# Доступные методы: count и index.
print('Количество синих цветов:', colors.count('синий'))  # сколько раз элемент встречается в кортеже
print('Индекс зелёного цвета:', colors.index('зелёный'))  # индекс элемента «зелёный»

# len — функция, которая возвращает количество элементов в кортеже.
print('Количество цветов:', len(colors))  # 3

print('Тип переменной colors:', type(colors))
